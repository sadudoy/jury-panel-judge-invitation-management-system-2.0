  async function load() {
    const params = new URLSearchParams();
    if (filters.q) params.set('q', filters.q);
    if (filters.judgeType) params.set('judgeType', filters.judgeType);
    if (filters.isActive) params.set('isActive', filters.isActive);
    if (filters.invitationStatus) params.set('invitationStatus', filters.invitationStatus);

    const tbodyWrap = container.querySelector('#judges-table-wrap');
    if (tbodyWrap) {
      tbodyWrap.innerHTML = renderLoading('Fetching judges...');
    }

    try {
      const data = await apiFetch(`/api/judges?${params.toString()}`);
      latestJudges = data.judges || [];
      const validIds = new Set(latestJudges.filter(isJudgeInvitable).map((j) => j.id));
      for (const id of Array.from(selectedIds)) {
        if (!validIds.has(id)) selectedIds.delete(id);
      }
      renderTable(latestJudges);
      updateSelectionUI();
    } catch (err) {
      if (tbodyWrap) tbodyWrap.innerHTML = renderError(err.message);
    }
  }

