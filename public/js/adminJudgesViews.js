function renderAccountStatusBadge(judge) {
  if (!judge.has_account) {
    return statusTag('NO_ACCOUNT');
  }
  if (!judge.is_active || judge.user_is_active === false) {
    return statusTag('ACCOUNT_DISABLED');
  }
  return statusTag('ACCOUNT_CREATED');
}

function isJudgeInvitable(judge) {
  return Boolean(
    judge.is_active &&
      (!judge.invitation_status ||
        judge.invitation_status === 'EXPIRED' ||
        judge.invitation_status === 'CANCELLED')
  );
}

async function copyTextToClipboard(text) {
  if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
    await navigator.clipboard.writeText(text);
    return true;
  }
  return false;
}

