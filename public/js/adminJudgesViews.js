function countCsvDataRowsClient(text) {
  const clean = (text || '').replace(/^\uFEFF/, '').trim();
  if (!clean) return 0;
  const lines = clean.split(/\r?\n/).filter((l) => l.trim().length > 0);
  return Math.max(0, lines.length - 1);
}

