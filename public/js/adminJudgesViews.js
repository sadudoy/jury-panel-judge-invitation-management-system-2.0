function openSendInvitationsModal(preselectedJudges, onSent) {
  openModal({
    title: 'Send Fest Invitations',
    large: true,
    bodyHtml: `<div id="send-inv-body">${renderLoading('Loading eligible judges...')}</div>`,
    onMount: async (root) => {
      const body = root.querySelector('#send-inv-body');
      try {
        let candidates = preselectedJudges;
        if (!candidates) {
          const data = await apiFetch('/api/judges?isActive=true');
          candidates = (data.judges || []).filter(
            (j) => !j.invitation_status || j.invitation_status === 'EXPIRED' || j.invitation_status === 'CANCELLED'
          );
        }

        if (candidates.length === 0) {
          body.innerHTML = renderEmpty(
            'No eligible uninvited judges',
            'All active judges already have a PENDING, ACCEPTED, or REJECTED fest invitation.'
          );
          return;
        }

        const defaultExp = toLocalDatetimeInputValue(new Date(Date.now() + 7 * 86400_000).toISOString());

        body.innerHTML = `
          <form id="send-inv-form">
            <div class="form-group">
              <label for="inv-deadline">Response Deadline</label>
              <input id="inv-deadline" class="input" type="datetime-local" required value="${escapeHtml(defaultExp)}" />
              <span class="form-hint">Unanswered invitations automatically expire after this deadline.</span>
            </div>
            <div class="form-group">
              <div style="display:flex; justify-content:space-between; align-items:center;">
                <label>Select Judges (${candidates.length} eligible)</label>
                <button type="button" class="btn btn-sm" id="toggle-all-inv">Toggle All</button>
              </div>
              <div style="max-height:260px; overflow-y:auto; border:1px solid var(--border); border-radius:8px; padding:8px; display:flex; flex-direction:column; gap:6px;">
                ${candidates
                  .map(
                    (j) => `
                  <label class="checkbox-row" style="padding:6px 8px; border-radius:6px; background:var(--bg-subtle);">
                    <input type="checkbox" class="inv-judge-chk" value="${j.id}" ${preselectedJudges ? 'checked' : ''} />
                    <span style="flex:1;">
                      <strong>${escapeHtml(j.name)}</strong>
                      <span class="cell-meta"> · ${escapeHtml(j.judge_type)} · ${escapeHtml(j.institution)}</span>
                    </span>
                    ${j.invitation_status ? statusTag(j.invitation_status) : ''}
                  </label>`
                  )
                  .join('')}
              </div>
            </div>
            <div style="display:flex; justify-content:flex-end; gap:10px; margin-top:16px;">
              <button type="button" class="btn" id="inv-cancel-modal">Cancel</button>
              <button type="submit" class="btn btn-primary" id="inv-send-submit">Send Invitations</button>
            </div>
          </form>
        `;

        root.querySelector('#inv-cancel-modal').addEventListener('click', closeModal);
        root.querySelector('#toggle-all-inv').addEventListener('click', () => {
          const chks = Array.from(root.querySelectorAll('.inv-judge-chk'));
          const allChecked = chks.every((c) => c.checked);
          chks.forEach((c) => {
            c.checked = !allChecked;
          });
        });

        root.querySelector('#send-inv-form').addEventListener('submit', async (e) => {
          e.preventDefault();
          const judgeIds = Array.from(root.querySelectorAll('.inv-judge-chk:checked')).map((c) =>
            Number(c.value)
          );
          if (judgeIds.length === 0) {
            showToast('Select at least one judge.', 'warning');
            return;
          }
          const deadlineVal = root.querySelector('#inv-deadline').value;
          const expirationDate = new Date(deadlineVal).toISOString();

          const btn = root.querySelector('#inv-send-submit');
          btn.disabled = true;
          try {
            const res = await apiFetch('/api/invitations/send', {
              method: 'POST',
              body: { judgeIds, expirationDate },
            });
            closeModal();
            showToast(`Sent ${res.sent.length} invitation(s).`, 'success');
            onSent();
          } catch (err) {
            showToast(err.message, 'error');
          } finally {
            btn.disabled = false;
          }
        });
      } catch (err) {
        body.innerHTML = renderError(err.message);
      }
    },
  });
}

export async function renderAdminInvitations(container) {
  const filters = { q: '', status: '', judgeType: '' };

  async function load() {
    const params = new URLSearchParams();
    if (filters.q) params.set('q', filters.q);
    if (filters.status) params.set('status', filters.status);
    if (filters.judgeType) params.set('judgeType', filters.judgeType);

    const wrap = container.querySelector('#inv-table-wrap');
    if (wrap) wrap.innerHTML = renderLoading('Loading invitations...');

    try {
      const data = await apiFetch(`/api/invitations?${params.toString()}`);
      renderTable(data.invitations || []);
    } catch (err) {
      if (wrap) wrap.innerHTML = renderError(err.message);
    }
  }

  function renderShell() {
    container.innerHTML = `
      <div class="page-header">
        <div>
          <h1 class="page-title">Fest Invitations</h1>
          <p class="page-subtitle">Send single or bulk invitations, manage response deadlines, and track judge responses (one invitation per judge).</p>
        </div>
        <div class="header-actions">
          <button type="button" class="btn" id="inv-expire-btn">
            <i data-lucide="clock"></i>
            <span>Expire Overdue</span>
          </button>
          <button type="button" class="btn btn-primary" id="inv-send-btn">
            <i data-lucide="send"></i>
            <span>Send Invitations</span>
          </button>
        </div>
      </div>

      <div class="card">
        <div class="filter-bar">
          <div class="search-input-wrap">
            <i data-lucide="search"></i>
            <input id="inv-search" class="input" type="search" placeholder="Search judge or institution..." />
          </div>
          <select id="inv-status-filter" class="input" style="width:auto; min-width:150px;">
            <option value="">All Statuses</option>
            <option value="PENDING">Pending</option>
            <option value="ACCEPTED">Accepted</option>
            <option value="REJECTED">Rejected</option>
            <option value="EXPIRED">Expired</option>
            <option value="CANCELLED">Cancelled</option>
          </select>
          <select id="inv-type-filter" class="input" style="width:auto; min-width:140px;">
            <option value="">All Types</option>
            <option value="EXTERNAL">External</option>
            <option value="FACULTY">Faculty</option>
          </select>
        </div>
        <div class="table-wrap" id="inv-table-wrap">${renderLoading('Loading invitations...')}</div>
      </div>
    `;
    refreshIcons(container);

    container.querySelector('#inv-send-btn').addEventListener('click', () => {
      openSendInvitationsModal(null, load);
    });

    container.querySelector('#inv-expire-btn').addEventListener('click', async () => {
      try {
        const res = await apiFetch('/api/invitations/expire-overdue', { method: 'POST' });
        showToast(`Expired ${res.expiredCount} overdue invitation(s).`, 'success');
        load();
      } catch (err) {
        showToast(err.message, 'error');
      }
    });

    let debounce;
    container.querySelector('#inv-search').addEventListener('input', (e) => {
      filters.q = e.target.value.trim();
      clearTimeout(debounce);
      debounce = setTimeout(load, 220);
    });
    container.querySelector('#inv-status-filter').addEventListener('change', (e) => {
      filters.status = e.target.value;
      load();
    });
    container.querySelector('#inv-type-filter').addEventListener('change', (e) => {
      filters.judgeType = e.target.value;
      load();
    });
  }

  function renderTable(invitations) {
    const wrap = container.querySelector('#inv-table-wrap');
    if (invitations.length === 0) {
      wrap.innerHTML = renderEmpty(
        'No invitations found',
        'Send fest invitations to active judges so accepted judges can be allocated to competitions.',
        '<button type="button" class="btn btn-primary btn-sm" id="empty-send-inv">Send Invitations</button>'
      );
      wrap.querySelector('#empty-send-inv')?.addEventListener('click', () => openSendInvitationsModal(null, load));
      return;
    }

    wrap.innerHTML = `
      <table>
        <thead>
          <tr>
            <th>Judge</th>
            <th>Type</th>
            <th>Sent Date</th>
            <th>Deadline</th>
            <th>Status</th>
            <th>Response Date</th>
            <th class="td-right">Resends</th>
            <th class="td-right">Actions</th>
          </tr>
        </thead>
        <tbody>
          ${invitations
            .map(
              (inv) => `
            <tr>
              <td>
                <a href="#/admin/judges/${inv.judge_id}" class="cell-title">${escapeHtml(inv.judge_name)}</a>
                <div class="cell-meta">${escapeHtml(inv.institution)} · ${escapeHtml(inv.judge_email)}</div>
              </td>
              <td>${statusTag(inv.judge_type)}</td>
              <td class="mono" style="font-size:12px;">${escapeHtml(formatDateTime(inv.sent_date))}</td>
              <td class="mono" style="font-size:12px;">${escapeHtml(formatDateTime(inv.expiration_date))}</td>
              <td>${statusTag(inv.response_status)}</td>
              <td class="mono" style="font-size:12px;">${escapeHtml(formatDateTime(inv.response_date))}</td>
              <td class="td-right mono">${inv.resend_count}</td>
              <td class="td-right">
                <div class="td-actions">
                  ${
                    ['PENDING', 'EXPIRED', 'CANCELLED'].includes(inv.response_status) && inv.judge_is_active
                      ? `<button type="button" class="btn btn-sm resend-inv-btn" data-id="${inv.id}">Resend</button>`
                      : ''
                  }
                  ${
                    inv.response_status === 'PENDING' ||
                    (inv.response_status === 'ACCEPTED' && inv.active_assignments_count === 0)
                      ? `<button type="button" class="btn btn-sm btn-danger cancel-inv-btn" data-id="${inv.id}">Cancel</button>`
                      : ''
                  }
                </div>
              </td>
            </tr>`
            )
            .join('')}
        </tbody>
      </table>
    `;

    const byId = new Map(invitations.map((i) => [i.id, i]));

    wrap.querySelectorAll('.resend-inv-btn').forEach((btn) => {
      btn.addEventListener('click', () => {
        const inv = byId.get(Number(btn.dataset.id));
        const defaultExp = toLocalDatetimeInputValue(new Date(Date.now() + 5 * 86400_000).toISOString());
        openModal({
          title: `Resend Invitation – ${inv.judge_name}`,
          bodyHtml: `
            <form id="resend-inv-form">
              <div class="form-group">
                <label for="resend-exp">New Expiration Deadline</label>
                <input id="resend-exp" class="input" type="datetime-local" required value="${escapeHtml(defaultExp)}" />
              </div>
              <div style="display:flex; justify-content:flex-end; gap:10px; margin-top:16px;">
                <button type="button" class="btn" id="resend-cancel">Cancel</button>
                <button type="submit" class="btn btn-primary">Resend Invitation</button>
              </div>
            </form>
          `,
          onMount: (root) => {
            root.querySelector('#resend-cancel').addEventListener('click', closeModal);
            root.querySelector('#resend-inv-form').addEventListener('submit', async (e) => {
              e.preventDefault();
              try {
                const expirationDate = new Date(root.querySelector('#resend-exp').value).toISOString();
                await apiFetch(`/api/invitations/${inv.id}/resend`, {
                  method: 'POST',
                  body: { expirationDate },
                });
                closeModal();
                showToast('Invitation resent.', 'success');
                load();
              } catch (err) {
                showToast(err.message, 'error');
              }
            });
          },
        });
      });
    });

    wrap.querySelectorAll('.cancel-inv-btn').forEach((btn) => {
      btn.addEventListener('click', async () => {
        const id = Number(btn.dataset.id);
        try {
          await apiFetch(`/api/invitations/${id}/cancel`, { method: 'POST' });
          showToast('Invitation cancelled.', 'success');
          load();
        } catch (err) {
          showToast(err.message, 'error');
        }
      });
    });
  }

  renderShell();
  await load();
}